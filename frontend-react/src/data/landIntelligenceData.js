function riskLevelFromScore(score) {
  if (score >= 75) return 'High'
  if (score >= 45) return 'Medium'
  return 'Low'
}

function buildParcel(raw) {
  const encroachmentArea = Math.max(0, raw.detectedArea - raw.authorizedArea)
  const encroachmentPercentage = raw.authorizedArea
    ? Number(((encroachmentArea / raw.authorizedArea) * 100).toFixed(1))
    : 0

  return {
    ...raw,
    encroachmentArea,
    encroachmentPercentage,
    riskLevel: riskLevelFromScore(raw.riskScore),
    dataSource: DATA_SOURCE_LABEL,
  }
}

